// Command gen generates frontend provider presets from the Go registry.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/CHE3MZ/kaid/internal/llm"
)

// preset contains only built-in metadata, never resolved user configuration or
// credentials. Keep the JSON field names aligned with KaidProviderPreset.
type preset struct {
	Name        string   `json:"name"`
	DisplayName string   `json:"displayName"`
	Protocol    string   `json:"protocol"`
	BaseURL     string   `json:"baseUrl"`
	AuthHeader  string   `json:"authHeader,omitempty"`
	EnvVar      string   `json:"envVar"`
	AmbientAuth bool     `json:"ambientAuth,omitempty"`
	Models      []string `json:"models"`
}

const header = `// SPDX-License-Identifier: Apache-2.0
// Copyright 2026 alibaba/open-code-review Contributors

// Code generated by go generate ./internal/llm; DO NOT EDIT.
// Source: internal/llm/providers.go. Providers are sorted by name; model order is preserved.

import type { KaidProviderPreset } from './providers';

export const PROVIDER_PRESETS: KaidProviderPreset[] = `

func main() {
	output := flag.String("output", "", "path to the generated TypeScript file")
	checkOnly := flag.Bool("check", false, "verify the provider presets without writing files")
	flag.Parse()
	var err error
	if *checkOnly {
		err = check(*output)
	} else {
		err = generate(*output)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(output string) error {
	if output == "" {
		return fmt.Errorf("-output path is required; run go generate ./internal/llm from the repository root")
	}
	providers := llm.ListProviders()
	data, err := render(providers)
	if err != nil {
		return err
	}
	if err := writeFileAtomically(output, data, 0o644); err != nil {
		return fmt.Errorf("write provider presets: %w", err)
	}
	return nil
}

func writeFileAtomically(output string, data []byte, perm os.FileMode) error {
	dir := filepath.Dir(output)
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(output)+".tmp-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)

	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(perm); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Rename(tmpName, output); err != nil {
		return err
	}
	return nil
}

func render(providers []llm.Provider) ([]byte, error) {
	if err := validateModelLists(providers); err != nil {
		return nil, err
	}
	presets := make([]preset, 0, len(providers))
	for _, p := range providers {
		models := append([]string{}, p.Models...)
		presets = append(presets, preset{
			Name:        p.Name,
			DisplayName: p.DisplayName,
			Protocol:    p.Protocol,
			BaseURL:     p.BaseURL,
			AuthHeader:  p.AuthHeader,
			EnvVar:      p.EnvVar,
			AmbientAuth: p.AmbientAuth,
			Models:      models,
		})
	}
	data, err := json.MarshalIndent(presets, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("encode provider presets: %w", err)
	}
	return []byte(header + string(data) + ";\n"), nil
}

func validateModelLists(providers []llm.Provider) error {
	for _, provider := range providers {
		seen := make(map[string]bool, len(provider.Models))
		for _, model := range provider.Models {
			if seen[model] {
				return fmt.Errorf("provider %q has duplicate model %q", provider.Name, model)
			}
			seen[model] = true
		}
	}
	return nil
}
